// Builds js/schools/rice/crosslist.js from a JSON map { "STAT 310": ["ECON 307"], ... }
// Usage: node tools/gen-crosslist.mjs path/to/crosslist.json
import { readFileSync, writeFileSync } from 'node:fs';
const map = JSON.parse(readFileSync(process.argv[2], 'utf8'));
// make symmetric + transitive closure
const adj = new Map();
const link = (a, b) => { if (!adj.has(a)) adj.set(a, new Set()); adj.get(a).add(b); };
for (const [k, vs] of Object.entries(map)) for (const v of vs) { link(k, v); link(v, k); }
const out = {};
for (const start of adj.keys()) {
  const seen = new Set([start]); const stack = [start];
  while (stack.length) { const c = stack.pop(); for (const n of adj.get(c) || []) if (!seen.has(n)) { seen.add(n); stack.push(n); } }
  seen.delete(start); out[start] = [...seen].sort();
}
const body = Object.keys(out).sort().map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(out[k])},`).join('\n');
writeFileSync('js/schools/rice/crosslist.js', `// Generated by tools/gen-crosslist.mjs from the Rice General Announcements. Cross-listed course equivalents.\nexport default {\n${body}\n};\n`);
console.log(`wrote crosslist with ${Object.keys(out).length} codes`);
